-- Campaign console (Next.js).
--
-- These rows are outreach targets: an address, a decision maker, and a
-- send history. They are not valuation listings. Listing price, sqft, and
-- tenant ownership live in the valuation schema (see
-- 20251121160000_valuation_schema.sql). Sharing one table named
-- "properties" would make one of the two apps wrong.

create extension if not exists pgcrypto;
create extension if not exists pg_trgm;

-- ---------------------------------------------------------------------------
-- properties: one row per building we might email
-- Shape matches lib/types.ts Property.
-- ---------------------------------------------------------------------------
create table public.properties (
  id                          uuid primary key default gen_random_uuid(),
  property_address            text,
  zip_code                    text,
  city                        text,
  county                      text,
  state                       text,
  decision_maker_name         text,
  decision_maker_email        text,
  decision_maker_phone        text,
  hoa_or_management_company   text,
  suspend_until               date not null default current_date,
  opt_out_code                uuid not null default gen_random_uuid(),
  created_at                  timestamptz not null default timezone('utc', now()),
  updated_at                  timestamptz not null default timezone('utc', now()),
  constraint properties_opt_out_code_key unique (opt_out_code),
  constraint properties_email_shape check (
    decision_maker_email is null
    or decision_maker_email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'
  )
);

-- Upload dedupe is an exact address match (process-properties .in("property_address")).
-- A unique index is what keeps two overlapping batches from inserting the same building.
create unique index properties_address_key
  on public.properties (property_address)
  where property_address is not null;

create index properties_state_city_idx
  on public.properties (state, city, county);

create index properties_address_trgm_idx
  on public.properties using gin (property_address gin_trgm_ops);

create index properties_suspend_idx
  on public.properties (suspend_until)
  where suspend_until > current_date;

-- ---------------------------------------------------------------------------
-- email_templates
-- ---------------------------------------------------------------------------
create table public.email_templates (
  id            integer generated by default as identity primary key,
  template_name text not null,
  subject       text,
  hook          text,
  body          text not null,
  signature     text,
  is_active     boolean not null default true,
  created_at    timestamptz not null default timezone('utc', now()),
  updated_at    timestamptz not null default timezone('utc', now()),
  constraint email_templates_name_key unique (template_name)
);

create index email_templates_active_idx
  on public.email_templates (is_active, created_at desc);

-- ---------------------------------------------------------------------------
-- email_logs: the high-volume table. One row per send.
-- Dashboard filters on replied, campaign_day, sent_at.
-- ---------------------------------------------------------------------------
create table public.email_logs (
  id            uuid primary key default gen_random_uuid(),
  property_id   uuid not null references public.properties (id) on delete cascade,
  template_id   integer not null references public.email_templates (id),
  campaign_day  integer not null default 1 check (campaign_day >= 1),
  replied       boolean not null default false,
  email_id      text not null,
  thread_id     text not null,
  sent_at       timestamptz not null default timezone('utc', now()),
  replied_at    timestamptz,
  constraint email_logs_thread_key unique (thread_id),
  constraint email_logs_reply_time check (
    replied_at is null or replied_at >= sent_at
  )
);

create index email_logs_sent_idx
  on public.email_logs (sent_at desc);

create index email_logs_property_sent_idx
  on public.email_logs (property_id, sent_at desc);

create index email_logs_campaign_idx
  on public.email_logs (campaign_day, sent_at desc);

-- Reply rate is count(replied) / count(*). A partial index keeps that scan small
-- once the log is in the hundreds of thousands.
create index email_logs_replied_idx
  on public.email_logs (replied_at)
  where replied;

-- ---------------------------------------------------------------------------
-- campaign_progress: singleton-style cursor (the app reads the latest id)
-- ---------------------------------------------------------------------------
create table public.campaign_progress (
  id            integer generated by default as identity primary key,
  current_day   integer not null default 1 check (current_day >= 1),
  last_sent_at  timestamptz not null default timezone('utc', now()),
  pdf_url       text not null default ''
);

-- ---------------------------------------------------------------------------
-- invites: one outstanding invite per email. invited_by is an auth user.
-- ---------------------------------------------------------------------------
create table public.invites (
  id          uuid primary key default gen_random_uuid(),
  email       text not null,
  invited_by  uuid not null references auth.users (id) on delete cascade,
  user_id     uuid references auth.users (id) on delete set null,
  message     text,
  created_at  timestamptz not null default timezone('utc', now()),
  constraint invites_email_key unique (email),
  constraint invites_email_shape check (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);

create index invites_invited_by_idx on public.invites (invited_by, created_at desc);

-- ---------------------------------------------------------------------------
-- request_tracker: one row per UTC day. The app caps process-properties at 1500.
-- ---------------------------------------------------------------------------
create table public.request_tracker (
  id                            bigint generated by default as identity primary key,
  date                          date not null,
  process_properties_requests   integer not null default 0 check (process_properties_requests >= 0),
  created_at                    timestamptz not null default timezone('utc', now()),
  updated_at                    timestamptz not null default timezone('utc', now()),
  constraint request_tracker_date_key unique (date)
);
